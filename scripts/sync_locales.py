"""Regenerate Flutter language metadata from server/app/locales.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
locales = json.loads((ROOT / 'server/app/locales.json').read_text())
lines = ["// Generated by scripts/sync_locales.py; edit server/app/locales.json.",
         "import 'package:flutter/widgets.dart';", '', 'const appLocaleNames = {']
for tag, meta in locales.items():
    lines.append(f"  '{tag}': {json.dumps(meta['name'], ensure_ascii=False)},")
lines += ['};', '', 'const supportedAppLocales = [']
for tag in locales:
    parts = tag.split('-')
    if len(parts) == 1:
        value = f"Locale('{tag}')"
    else:
        fields = [f"languageCode: '{parts[0]}'"]
        for part in parts[1:]:
            fields.append(f"{'scriptCode' if len(part) == 4 else 'countryCode'}: '{part}'")
        value = 'Locale.fromSubtags(' + ', '.join(fields) + ')'
    lines.append(f'  {value},')
lines += ['];', '']
(ROOT / 'app/app_core/lib/src/supported_locales.dart').write_text('\n'.join(lines))

# Declare every language to iOS and include its permission strings in the bundle.
import hashlib
import re
for app in ['app_student', 'app_student_appstore', 'app_parent_appstore']:
    ios = ROOT / 'app' / app / 'ios'
    plist = ios / 'Runner/Info.plist'
    content = plist.read_text()
    content = re.sub(
        r'(<key>CFBundleLocalizations</key>\s*<array>).*?(\s*</array>)',
        lambda match: match[1] + '\n' + ''.join(
            '\t\t<string>' + tag + '</string>\n' for tag in locales
        ) + '\t</array>', content, count=1, flags=re.S,
    )
    plist.write_text(content)
    project = ios / 'Runner.xcodeproj/project.pbxproj'
    content = project.read_text()
    children = []
    references = []
    for tag in locales:
        existing = re.search(r'([A-F0-9]{24}) /\* ' + re.escape(tag) + r' \*/ = \{isa = PBXFileReference;[^\n]*InfoPlist.strings[^\n]*', content)
        ref = existing[1] if existing else hashlib.sha256((app + '/InfoPlist/' + tag).encode()).hexdigest()[:24].upper()
        if not existing:
            references.append(f'\t\t{ref} /* {tag} */ = {{isa = PBXFileReference; lastKnownFileType = text.plist.strings; name = "{tag}"; path = "{tag}.lproj/InfoPlist.strings"; sourceTree = "<group>"; }};\n')
        children.append(f'\t\t\t\t{ref} /* {tag} */,\n')
    content = content.replace('/* End PBXFileReference section */', ''.join(references) + '/* End PBXFileReference section */')
    content, count = re.subn(
        r'(/\* InfoPlist.strings \*/ = \{\s*isa = PBXVariantGroup;\s*children = \().*?(\s*\);)',
        lambda match: match[1] + '\n' + ''.join(children) + '\t\t\t);',
        content, count=1, flags=re.S,
    )
    assert count == 1, f'Missing InfoPlist.strings group: {app}'
    content = re.sub(r'(knownRegions = \().*?(\s*\);)',
                     lambda match: match[1] + '\n\t\t\t\tBase,\n' + ''.join(
                         f'\t\t\t\t"{tag}",\n' for tag in locales
                     ) + '\t\t\t);', content, count=1, flags=re.S)
    project.write_text(content)
